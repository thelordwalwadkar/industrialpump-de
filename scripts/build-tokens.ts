/**
 * Builds src/styles/tokens.css from src/styles/palette.json (client colours: background, primary navy, yellow highlight, sky blue).
 * Derives only tints/shades and accessible text-on-colour pairs. Fails when a text pair misses WCAG AA.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

type RGB = [number, number, number];
const hexToRgb = (h: string): RGB => {
  const m = /^#?([0-9a-f]{6})$/i.exec(h.trim());
  if (!m) throw new Error(`Invalid hex colour: ${h}`);
  const n = parseInt(m[1]!, 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
};
const rgbToHex = ([r, g, b]: RGB) =>
  '#' + [r, g, b].map((v) => Math.round(Math.min(255, Math.max(0, v))).toString(16).padStart(2, '0')).join('').toUpperCase();
const lum = ([r, g, b]: RGB) => {
  const f = (c: number) => { const s = c / 255; return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4; };
  return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b);
};
const contrast = (a: RGB, b: RGB) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x! + 0.05) / (y! + 0.05); };
const mix = (a: RGB, b: RGB, t: number): RGB => [0, 1, 2].map((i) => a[i]! * (1 - t) + b[i]! * t) as RGB;

const palette = JSON.parse(readFileSync('src/styles/palette.json', 'utf8')) as Record<string, { hex: string; status: string; note: string }>;
const bg = hexToRgb(palette.bg!.hex);
const primary = hexToRgb(palette.primary!.hex);
const highlight = hexToRgb(palette.overhaul!.hex);
const sky = hexToRgb(palette.sky!.hex);
const WHITE: RGB = [255, 255, 255];
const BLACK: RGB = [0, 0, 0];

/** Best text colour on `c`: the navy primary if it passes AA, otherwise white or black. */
const onColour = (c: RGB): RGB => {
  if (contrast(primary, c) >= 4.5) return primary;
  return contrast(c, WHITE) >= contrast(c, BLACK) ? WHITE : BLACK;
};
/** Darken `c` until it reaches `min` contrast on `onto`. */
const strongOn = (c: RGB, onto: RGB, min: number): RGB => {
  for (let t = 0; t <= 1.0001; t += 0.05) { const m = mix(c, BLACK, t); if (contrast(m, onto) >= min) return m; }
  return BLACK;
};

const surface = mix(bg, primary, 0.06);
const tokens: Record<string, RGB> = {
  '--color-bg': bg,
  '--color-surface': surface,
  '--color-primary': primary,
  '--color-primary-strong': primary,
  '--color-primary-soft': mix(bg, primary, 0.1),
  '--color-on-primary': WHITE,
  '--color-overhaul': highlight,
  '--color-on-overhaul': onColour(highlight),
  '--color-overhaul-strong': strongOn(highlight, bg, 4.5),
  '--color-overhaul-soft': mix(bg, highlight, 0.18),
  '--color-sky': sky,
  '--color-sky-deep': mix(sky, primary, 0.42),
  '--color-on-sky': WHITE,
  '--color-text': primary,
  '--color-text-muted': strongOn(mix(primary, bg, 0.32), bg, 4.5),
  '--color-border': mix(bg, primary, 0.16),
  '--color-focus': primary,
  '--color-focus-on-dark': highlight,
};

// Contrast gate: [foreground token, background token, min ratio, label]
const pairs: [string, string, number, string][] = [
  ['--color-text', '--color-bg', 4.5, 'Fliesstext (Navy) auf Weiss'],
  ['--color-text', '--color-surface', 4.5, 'Fliesstext auf grauer Flaeche'],
  ['--color-text-muted', '--color-bg', 4.5, 'Gedaempfter Text auf Weiss'],
  ['--color-text-muted', '--color-surface', 4.5, 'Gedaempfter Text auf grauer Flaeche'],
  ['--color-primary-strong', '--color-primary-soft', 4.5, 'Navy-Link auf Navy-Tint'],
  ['--color-on-primary', '--color-primary', 4.5, 'Weiss auf Navy (dunkle Abschnitte)'],
  ['--color-overhaul', '--color-primary', 4.5, 'Gelb auf Navy (Akzente, Links in dunklen Abschnitten)'],
  ['--color-on-overhaul', '--color-overhaul', 4.5, 'Navy auf Gelb (Buttons)'],
  ['--color-text', '--color-overhaul-soft', 4.5, 'Navy auf gelbem Tint'],
  ['--color-on-sky', '--color-sky-deep', 4.5, 'Weiss auf Himmelblau mit Navy-Schleier (Hero-Text)'],
  ['--color-overhaul', '--color-sky-deep', 3, 'Gelb auf Himmelblau mit Navy-Schleier (Hero-Akzente)'],
  ['--color-primary', '--color-bg', 3, 'Navy als UI-Element auf Weiss'],
  ['--color-focus', '--color-bg', 3, 'Fokusring auf Weiss'],
  ['--color-focus-on-dark', '--color-primary', 3, 'Fokusring auf dunklem Grund'],
];
const report = pairs.map(([fg, bgk, min, label]) => {
  const ratio = contrast(tokens[fg]!, tokens[bgk]!);
  return { fg, bg: bgk, label, min, ratio: Math.round(ratio * 100) / 100, pass: ratio >= min };
});

const css = [
  '/* GENERATED by scripts/build-tokens.ts from src/styles/palette.json - do not edit by hand. */',
  '/* Client colours: background, primary (navy), highlight (yellow), sky blue. Everything else is a derived tint/shade. */',
  ':root {',
  ...Object.entries(tokens).map(([k, v]) => `  ${k}: ${rgbToHex(v)};`),
  '  --color-highlight: var(--color-overhaul);',
  '  --color-on-highlight: var(--color-on-overhaul);',
  '}',
  '',
].join('\n');
writeFileSync('src/styles/tokens.css', css);
mkdirSync('.reports', { recursive: true });
writeFileSync('.reports/contrast.json', JSON.stringify(report, null, 2));
const failed = report.filter((r) => !r.pass);
console.log(`tokens.css written (${report.length} contrast pairs checked, ${failed.length} failing)`);
for (const f of failed) console.error(`  FAIL ${f.label}: ${f.fg} on ${f.bg} = ${f.ratio} (min ${f.min})`);
if (failed.length) process.exit(1);
